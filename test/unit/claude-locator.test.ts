// Ricerca di Claude Code (PATH, npm, estensione di VS Code) e registrazione MCP senza la CLI.
// EN: Finding Claude Code (PATH, npm, VS Code extension) and MCP registration without the CLI.
import fs from 'node:fs'
import path from 'node:path'
import { afterEach, beforeEach, describe, expect, it } from 'vitest'
import { locateClaude } from '../../src/node/claude-locator'
import { claudeConfigFile, registerMcp, registerProjectMcp, setupClaudeCode } from '../../src/node/integrations'
import { tmpHome } from '../helpers'

/** Crea un file (e le sue cartelle). / EN: Creates a file (and its folders). */
const touch = (file: string, text = '') => { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, text) }

describe('locateClaude', () => {
  it('trova claude.exe nel PATH (Windows)', () => {
    const home = tmpHome('cl-home')
    const bin = tmpHome('cl-bin')
    touch(path.join(bin, 'claude.exe'))
    const c = locateClaude('claude', { env: { PATH: `C:\\inesistente;${bin}` }, home, platform: 'win32' })
    expect(c).toEqual({ command: path.join(bin, 'claude.exe'), prefix: [], file: path.join(bin, 'claude.exe') })
  })

  it('claude.cmd di npm diventa "node cli.js", senza shell', () => {
    const home = tmpHome('cl-home')
    const npm = tmpHome('cl-npm')
    const cli = path.join(npm, 'node_modules', '@anthropic-ai', 'claude-code', 'cli.js')
    touch(cli)
    // Script generato da npm (cmd-shim): punta al cli.js relativo a %dp0%
    // EN: Script generated by npm (cmd-shim): points to cli.js relative to %dp0%
    touch(path.join(npm, 'claude.cmd'), '@ECHO off\r\nIF EXIST "%dp0%\\node.exe" (\r\n  SET "_prog=%dp0%\\node.exe"\r\n)\r\n"%_prog%"  "%dp0%\\node_modules\\@anthropic-ai\\claude-code\\cli.js" %*\r\n')
    const c = locateClaude('claude', { env: { PATH: npm }, home, platform: 'win32' })
    expect(c).toEqual({ command: process.execPath, prefix: [cli], file: path.join(npm, 'claude.cmd') })
  })

  it('claude.cmd senza cli.js raggiungibile non è utilizzabile', () => {
    const home = tmpHome('cl-home')
    const npm = tmpHome('cl-npm')
    touch(path.join(npm, 'claude.cmd'), '"%dp0%\\node_modules\\manca\\cli.js" %*')
    expect(locateClaude('claude', { env: { PATH: npm }, home, platform: 'win32' })).toBeNull()
  })

  it('solo l\'estensione di VS Code: usa il suo claude.exe, il più recente', () => {
    const home = tmpHome('cl-home')
    const ext = path.join(home, '.vscode', 'extensions')
    const old = path.join(ext, 'anthropic.claude-code-2.1.100-win32-x64', 'resources', 'native-binary', 'claude.exe')
    const nuovo = path.join(ext, 'anthropic.claude-code-2.1.301-win32-x64', 'resources', 'native-binary', 'claude.exe')
    touch(old)
    touch(nuovo)
    fs.utimesSync(old, new Date(2026, 0, 1), new Date(2026, 0, 1))
    expect(locateClaude('claude', { env: { PATH: '' }, home, platform: 'win32' })?.command).toBe(nuovo)
  })

  it('installer nativo in ~/.local/bin anche se non è nel PATH', () => {
    const home = tmpHome('cl-home')
    touch(path.join(home, '.local', 'bin', 'claude.exe'))
    expect(locateClaude('claude', { env: { PATH: '' }, home, platform: 'win32' })?.command).toBe(path.join(home, '.local', 'bin', 'claude.exe'))
  })

  it('percorso esplicito: si usa quello, se esiste', () => {
    const home = tmpHome('cl-home')
    const exe = path.join(tmpHome('cl-x'), 'mio-claude.exe')
    touch(exe)
    expect(locateClaude(exe, { env: { PATH: '' }, home, platform: 'win32' })?.command).toBe(exe)
    expect(locateClaude(exe + '.no', { env: { PATH: '' }, home, platform: 'win32' })).toBeNull()
  })

  it('niente da nessuna parte: null', () => {
    expect(locateClaude('claude', { env: { PATH: '' }, home: tmpHome('cl-home'), platform: 'win32' })).toBeNull()
  })
})

describe('registrazione MCP senza la CLI di Claude Code', () => {
  // Ambiente senza claude: PATH vuoto, cartella utente e configurazione di Claude Code temporanee
  // EN: Environment without claude: empty PATH, temporary user folder and Claude Code configuration
  const saved: Record<string, string | undefined> = {}
  const vars = ['PATH', 'Path', 'USERPROFILE', 'HOME', 'APPDATA', 'LOCALAPPDATA', 'CLAUDE_CONFIG_DIR']
  let cfgDir: string

  beforeEach(() => {
    for (const v of vars) saved[v] = process.env[v]
    const home = tmpHome('cl-user')
    cfgDir = tmpHome('cl-cfg')
    process.env.PATH = ''
    delete process.env.Path
    process.env.USERPROFILE = home
    process.env.HOME = home
    process.env.APPDATA = path.join(home, 'AppData', 'Roaming')
    process.env.LOCALAPPDATA = path.join(home, 'AppData', 'Local')
    process.env.CLAUDE_CONFIG_DIR = cfgDir
  })

  afterEach(() => {
    for (const v of vars) {
      if (saved[v] === undefined) delete process.env[v]
      else process.env[v] = saved[v]
    }
  })

  it('scrive la voce stdio in .claude.json e tiene il resto del file', () => {
    const file = claudeConfigFile()
    expect(file).toBe(path.join(cfgDir, '.claude.json'))
    fs.writeFileSync(file, JSON.stringify({ numStartups: 7, mcpServers: { altro: { type: 'stdio', command: 'x' }, micelio: { type: 'http', url: 'http://127.0.0.1:7337/mcp' } } }))
    const r = registerMcp('C:\\Users\\mario\\.micelio', 'C:\\Micelio\\dist\\cli\\main.js')
    expect(r).toEqual({ via: 'file', claude: null })
    const cfg = JSON.parse(fs.readFileSync(file, 'utf8'))
    expect(cfg.numStartups).toBe(7)
    expect(cfg.mcpServers.altro).toEqual({ type: 'stdio', command: 'x' })
    // La vecchia registrazione HTTP è sostituita dallo shim stdio
    // EN: The old HTTP registration is replaced by the stdio shim
    expect(cfg.mcpServers.micelio).toEqual({
      type: 'stdio',
      command: process.execPath.replace(/\\/g, '/'),
      args: ['C:/Micelio/dist/cli/main.js', '--home', 'C:/Users/mario/.micelio', 'mcp'],
      env: {}
    })
    expect(fs.existsSync(file + '.micelio-backup')).toBe(true)
  })

  it('.claude.json non valido: si ferma senza toccarlo', () => {
    const file = claudeConfigFile()
    fs.writeFileSync(file, '{ rotto')
    expect(() => registerMcp('C:\\h')).toThrow(/non è un JSON valido/)
    expect(fs.readFileSync(file, 'utf8')).toBe('{ rotto')
  })

  it('progetto: voce local sotto projects, riusando la chiave esistente', () => {
    const dir = tmpHome('cl-prog')
    const key = path.resolve(dir).replace(/\\/g, '/')
    // Su Windows Claude Code può aver salvato la cartella con maiuscole diverse
    // EN: On Windows Claude Code may have saved the folder with different case
    const stored = process.platform === 'win32' ? key.toUpperCase() : key
    fs.writeFileSync(claudeConfigFile(), JSON.stringify({ projects: { [stored]: { allowedTools: ['Bash'] } } }))
    const r = registerProjectMcp(dir, 'http://127.0.0.1:7337/mcp/abc', 'tok')
    expect(r.via).toBe('file')
    const cfg = JSON.parse(fs.readFileSync(claudeConfigFile(), 'utf8'))
    expect(Object.keys(cfg.projects)).toEqual([stored])
    expect(cfg.projects[stored]).toEqual({ allowedTools: ['Bash'], mcpServers: { micelio: { type: 'http', url: 'http://127.0.0.1:7337/mcp/abc', headers: { Authorization: 'Bearer tok' } } } })
  })

  it('avvisa se Claude Code non è mai stato usato da questo utente', () => {
    const setup = () => setupClaudeCode({ mcpUrl: 'u', token: 't', home: 'C:\\h', hook: false, context: false })
    const first = setup()
    expect(first.otherUser).toBe(true)
    expect(first.user.length).toBeGreaterThan(0)
    // Il .claude.json creato da Micelio non conta: l'avviso resta finché Claude Code non parte qui
    // EN: The .claude.json created by Micelio doesn't count: the warning stays until Claude Code runs here
    expect(setup().otherUser).toBe(true)
    // Claude Code avviato con questo utente: scrive i suoi campi
    // EN: Claude Code started with this user: it writes its own fields
    const cfg = JSON.parse(fs.readFileSync(claudeConfigFile(), 'utf8'))
    fs.writeFileSync(claudeConfigFile(), JSON.stringify({ ...cfg, numStartups: 1 }))
    expect(setup().otherUser).toBe(false)
  })

  it('le trascrizioni delle sessioni bastano a dire che Claude Code è usato qui', () => {
    fs.mkdirSync(path.join(cfgDir, 'projects'))
    expect(setupClaudeCode({ mcpUrl: 'u', token: 't', home: 'C:\\h', hook: false, context: false }).otherUser).toBe(false)
  })
})
